/**
 * @file    comms.c
 * @brief   USART2 receive (interrupt, one byte at a time) and transmit.
 *
 * How receiving works:
 *   1. comms_init() asks HAL to receive ONE byte with an interrupt.
 *   2. When it arrives, HAL calls HAL_UART_RxCpltCallback() (below).
 *   3. The callback feeds the byte to the line assembler (linebuf.c) and
 *      immediately asks for the next byte.
 *   4. When a full line is ready it is copied to s_line and s_ready is set.
 *   5. The main loop calls comms_get_line(), which hands the line over and
 *      clears s_ready. Until then, further complete lines are dropped
 *      (the box handles one command at a time, as the brief requires).
 */
#include "comms.h"
#include "linebuf.h"
#include "usart.h"     /* huart2, generated by CubeMX */
#include <string.h>

static uint8_t           s_rx_byte;                 /* byte HAL writes into     */
static linebuf_t         s_lb;                      /* line being assembled     */
static char              s_line[CMD_LINE_MAX + 1];  /* finished line for main   */
static volatile comms_result_t s_ready = COMMS_NONE; /* set by ISR, cleared by main */

/** Ask HAL for the next byte. */
static void start_rx(void)
{
    HAL_UART_Receive_IT(&huart2, &s_rx_byte, 1);
}

void comms_init(void)
{
    linebuf_reset(&s_lb);
    s_ready = COMMS_NONE;
    start_rx();
}

/* Called by HAL from the USART2 interrupt each time one byte has arrived. */
void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance != USART2) {
        return;
    }

    lb_result_t r = linebuf_push(&s_lb, (char)s_rx_byte);

    if (s_ready == COMMS_NONE) {          /* main loop is free to take a line */
        if (r == LB_LINE) {
            memcpy(s_line, s_lb.line, sizeof s_line);
            s_ready = COMMS_LINE;
        } else if (r == LB_OVERFLOW) {
            s_ready = COMMS_TOO_LONG;
        }
    }
    start_rx();                           /* keep listening */
}

/* Called by HAL on a UART error (noise, framing, overrun). Without this,
 * reception would stop after the first error and the box would go silent. */
void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
    if (huart->Instance == USART2) {
        start_rx();
    }
}

comms_result_t comms_get_line(char *out, size_t out_size)
{
    comms_result_t r = s_ready;

    if (r == COMMS_LINE) {
        strncpy(out, s_line, out_size - 1u);
        out[out_size - 1u] = '\0';
    }
    if (r != COMMS_NONE) {
        s_ready = COMMS_NONE;             /* allow the ISR to deliver the next line */
    }
    return r;
}

void comms_send(const char *data, size_t len)
{
    /* Blocking send. Timeout: 1 s plus ~0.1 ms per byte at 115200 baud. */
    HAL_UART_Transmit(&huart2, (const uint8_t *)data, (uint16_t)len,
                      1000u + (uint32_t)(len / 10u));
}

void comms_send_line(const char *text)
{
    comms_send(text, strlen(text));
    comms_send("\r\n", 2u);
}
